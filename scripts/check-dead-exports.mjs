const BASELINE_VERSION = 1;
const BASELINE_FILE = "scripts/baselines/dead-exports.json";
const CATEGORIES = ["zero-reference", "same-file-only", "test-only", "barrel-only"];
const CATEGORY_ORDER = new Map(CATEGORIES.map((category, index) => [category, index]));
const SOURCE_EXTENSION = /\.(?:[cm]?[jt]s|[jt]sx)$/i;
const DECLARATION_EXTENSION = /\.d\.[cm]?ts$/i;
const IGNORED_DIRECTORIES = new Set([
	".artifacts",
	".cache",
	".claude",
	".codegraph",
	".cursor",
	".devin",
	".git",
	".next",
	".nyc_output",
	".turbo",
	".vite",
	".webpack",
	"artifacts",
	"build",
	"coverage",
	"dist",
	"docs",
	"logs",
	"node_modules",
	"out",
	"plans",
	"playwright-report",
	"reports",
	"test-results",
]);
const TEST_SEGMENTS = new Set([
	"__e2e__",
	"__fixtures__",
	"__mocks__",
	"__snapshots__",
	"__specs__",
	"__tests__",
	"e2e",
	"fixture",
	"fixtures",
	"mock",
	"mocks",
	"snapshots",
	"spec",
	"specs",
	"test",
	"test-support",
	"tests",
]);
const TEST_FILE_PATTERN = /(?:^|\.)(?:e2e|fixture|fixtures|mock|mocks|spec|stories|test)(?:\.|$)/i;
const GENERATED_FILE_PATTERN = /(?:^|\.)generated(?:\.|$)/i;
const GENERATED_HEADER_PATTERN =
	/^\s*(?:\/\/|\/\*|\*).*?(?:@generated|auto-?generated|automatically generated|do not edit|generated by)/im;

function messageOf(error) {
	return error instanceof Error ? error.message : String(error);
}

function isRecord(value) {
	return value !== null && typeof value === "object" && !Array.isArray(value);
}

function flattenDiagnostic(diagnostic) {
	return ts.flattenDiagnosticMessageText(diagnostic.messageText, "\n");
}

function isDeclarationFile(fileName) {
	return DECLARATION_EXTENSION.test(fileName);
}

function isTestLikePath(fileName) {
	const normalized = fileName.replaceAll("\\", "/");
	const segments = normalized.split("/");
	if (segments.some((segment) => TEST_SEGMENTS.has(segment.toLowerCase()))) return true;
	const base = segments[segments.length - 1] ?? "";
	return TEST_FILE_PATTERN.test(base);
}

function isGeneratedPath(fileName) {
	const segments = fileName.replaceAll("\\", "/").split("/");
	if (segments.some((segment) => segment === "generated" || segment === "__generated__")) return true;
	const base = segments[segments.length - 1] ?? "";
	return GENERATED_FILE_PATTERN.test(base);
}

function isGeneratedSource(text) {
	return GENERATED_HEADER_PATTERN.test(text.slice(0, 2000));
}

function isWorkspaceFile(root, fileName) {
	const relativePath = portablePath(root, resolve(fileName));
	if (relativePath.startsWith("../") || relativePath === "..") return false;
	const segments = relativePath.split("/");
	return (
		(segments[0] === "packages" ||
			segments[0] === "scripts" ||
			(segments.length === 1 && SOURCE_EXTENSION.test(relativePath))) &&
		!segments.includes("node_modules")
	);
}

function isCandidateFile(root, fileName) {
	const relativePath = portablePath(root, resolve(fileName));
	if (!relativePath.startsWith("packages/")) return false;
	if (!relativePath.includes("/src/")) return false;
	if (isDeclarationFile(fileName) || isTestLikePath(relativePath) || isGeneratedPath(relativePath)) return false;
	return true;
}

function sourceFiles(root, directory, files) {
	if (!existsSync(directory)) return;
	const entries = readdirSync(directory, { withFileTypes: true });
	for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name, "en"))) {
		const path = join(directory, entry.name);
		if (entry.isDirectory()) {
			if (entry.name.startsWith(".") || IGNORED_DIRECTORIES.has(entry.name)) continue;
			sourceFiles(root, path, files);
			continue;
		}
		if (entry.isFile() && SOURCE_EXTENSION.test(entry.name) && !isGeneratedPath(portablePath(root, path))) {
			files.add(resolve(path));
		}
	}
}

function evidenceSourceFiles(root) {
	const files = new Set();
	sourceFiles(root, join(root, "packages"), files);
	sourceFiles(root, join(root, "scripts"), files);
	for (const entry of readdirSync(root, { withFileTypes: true })) {
		if (entry.isFile() && SOURCE_EXTENSION.test(entry.name)) files.add(join(root, entry.name));
	}
	return [...files].sort();
}

function sourceStem(relativePath) {
	const declarationStem = relativePath.replace(/\.d\.[cm]?ts$/i, "");
	if (declarationStem !== relativePath) return declarationStem;
	return relativePath.replace(SOURCE_EXTENSION, "");
}

function targetStems(target) {
	const cleaned = target.replace(/[?#].*$/, "").replace(/^\.\//, "");
	const stem = cleaned.replace(/\.d\.[cm]?ts$/i, "").replace(SOURCE_EXTENSION, "");
	if (!stem) return [];
	const stems = new Set([stem]);
	for (const [prefix, replacement] of [
		["dist/", "src/"],
		["build/", "src/"],
		["out/", "src/"],
		["lib/", "src/"],
	]) {
		if (stem.startsWith(prefix)) stems.add(`${replacement}${stem.slice(prefix.length)}`);
	}
	if (!stem.startsWith("src/")) stems.add(`src/${stem}`);
	return [...stems];
}

function isCodeTarget(target) {
	const cleaned = target.replace(/[?#].*$/, "");
	if (cleaned.endsWith("package.json")) return false;
	return (
		SOURCE_EXTENSION.test(cleaned) || (cleaned.includes("*") && SOURCE_EXTENSION.test(cleaned.replaceAll("*", "x")))
	);
}

function collectManifestTargets(value, targets) {
	if (typeof value === "string") {
		if (isCodeTarget(value)) targets.add(value);
		return;
	}
	if (Array.isArray(value)) {
		for (const entry of value) collectManifestTargets(entry, targets);
		return;
	}
	if (isRecord(value)) {
		for (const entry of Object.values(value)) collectManifestTargets(entry, targets);
	}
}

function entrypointTargets(manifest) {
	const targets = new Set();
	for (const field of [manifest.main, manifest.types, manifest.typings]) collectManifestTargets(field, targets);
	collectManifestTargets(manifest.exports, targets);
	return [...targets].sort((left, right) => left.localeCompare(right, "en"));
}

function resolveEntrypointSources(target, stems) {
	const matches = new Map();
	for (const candidate of targetStems(target)) {
		if (!candidate.includes("*")) {
			const file = stems.get(candidate);
			if (file) matches.set(file, true);
			continue;
		}
		const star = candidate.indexOf("*");
		const prefix = candidate.slice(0, star);
		const suffix = candidate.slice(star + 1);
		for (const [stem, file] of stems) {
			if (stem.length < prefix.length + suffix.length) continue;
			if (!stem.startsWith(prefix) || !stem.endsWith(suffix)) continue;
			matches.set(file, true);
		}
	}
	return [...matches.keys()].sort();
}

function publicEntrypoints(workspace, program, root, diagnostics) {
	const files = new Set();
	const packages = [];
	for (const pkg of workspace.packages) {
		if (pkg.manifest.private) continue;
		const targets = entrypointTargets(pkg.manifest);
		if (targets.length === 0) continue;
		const stems = new Map();
		for (const file of pkg.files) {
			// Ambient declaration inputs do not produce dist entrypoints.
			if (isDeclarationFile(file)) continue;
			stems.set(sourceStem(portablePath(pkg.directory, file)), file);
		}
		let packageMatched = 0;
		for (const target of targets) {
			const resolved = resolveEntrypointSources(target, stems);
			if (resolved.length === 0) {
				diagnostics.push({
					severity: "error",
					message: `No source file for public entrypoint ${pkg.manifest.name ?? pkg.relativePath}: ${target}`,
				});
				continue;
			}
			for (const file of resolved) {
				if (!program.getSourceFile(file)) {
					diagnostics.push({
						severity: "error",
						message: `Public entrypoint source is not in the program: ${portablePath(root, file)}`,
					});
					continue;
				}
				files.add(file);
				packageMatched++;
			}
		}
		packages.push({ name: pkg.manifest.name ?? pkg.relativePath, files: packageMatched });
	}
	return { files, packages };
}

function resolveAlias(checker, symbol) {
	const seen = new Set();
	let current = symbol ? checker.getMergedSymbol(symbol) : undefined;
	while (current && current.flags & ts.SymbolFlags.Alias && !seen.has(current)) {
		seen.add(current);
		let next;
		try {
			next = checker.getAliasedSymbol(current);
		} catch {
			break;
		}
		if (!next || next === current) break;
		current = checker.getMergedSymbol(next);
	}
	return current;
}

function isModuleSymbol(symbol) {
	return Boolean(symbol.flags & (ts.SymbolFlags.ValueModule | ts.SymbolFlags.NamespaceModule));
}

function symbolSourceFile(symbol) {
	for (const declaration of symbol.declarations ?? []) {
		const source = declaration.getSourceFile();
		if (source) return source;
	}
	return undefined;
}

function moduleExports(checker, sourceFile) {
	const module = checker.getSymbolAtLocation(sourceFile);
	return module ? checker.getExportsOfModule(module) : [];
}

function exportSymbol(sourceFile, checker, name) {
	return moduleExports(checker, sourceFile).find((symbol) => symbol.getName() === name);
}

function localExportTarget(checker, specifier) {
	const node = specifier.propertyName ?? specifier.name;
	const symbol = checker.getSymbolAtLocation(node);
	return symbol ? resolveAlias(checker, symbol) : undefined;
}

function exportDeclarationOfSpecifier(specifier) {
	const named = specifier.parent;
	if (!ts.isNamedExports(named) || !ts.isExportDeclaration(named.parent)) return undefined;
	return named.parent;
}

function isTopLevelDeclaration(declaration) {
	let current = declaration.parent;
	while (current && !ts.isSourceFile(current)) {
		if (
			ts.isBlock(current) ||
			ts.isModuleBlock(current) ||
			ts.isFunctionLike(current) ||
			ts.isClassLike(current) ||
			ts.isCaseBlock(current) ||
			ts.isCatchClause(current)
		) {
			return false;
		}
		current = current.parent;
	}
	return Boolean(current && ts.isSourceFile(current));
}

function isLocalTopLevelDeclaration(symbol, sourceFile) {
	return (symbol.declarations ?? []).some(
		(declaration) => declaration.getSourceFile() === sourceFile && isTopLevelDeclaration(declaration),
	);
}

function isDeclarationName(node) {
	const parent = node.parent;
	if (!parent) return false;
	if (
		parent.name === node &&
		(ts.isFunctionDeclaration(parent) ||
			ts.isFunctionExpression(parent) ||
			ts.isClassDeclaration(parent) ||
			ts.isClassExpression(parent) ||
			ts.isInterfaceDeclaration(parent) ||
			ts.isTypeAliasDeclaration(parent) ||
			ts.isEnumDeclaration(parent) ||
			ts.isEnumMember(parent) ||
			ts.isModuleDeclaration(parent) ||
			ts.isVariableDeclaration(parent) ||
			ts.isBindingElement(parent) ||
			ts.isParameter(parent) ||
			ts.isPropertyDeclaration(parent) ||
			ts.isPropertySignature(parent) ||
			ts.isMethodDeclaration(parent) ||
			ts.isMethodSignature(parent) ||
			ts.isGetAccessorDeclaration(parent) ||
			ts.isSetAccessorDeclaration(parent) ||
			ts.isTypeParameterDeclaration(parent) ||
			ts.isImportEqualsDeclaration(parent) ||
			ts.isPropertyAssignment(parent))
	) {
		return true;
	}
	if (ts.isImportSpecifier(parent) && parent.name === node && parent.propertyName) return false;
	if (ts.isNamespaceImport(parent) && parent.name === node) return true;
	if (ts.isExportSpecifier(parent)) {
		const declaration = exportDeclarationOfSpecifier(parent);
		if (declaration && !declaration.moduleSpecifier) return true;
	}
	if (ts.isNamespaceExport(parent) && parent.name === node) return true;
	if (ts.isExportAssignment(parent) && parent.expression === node) return true;
	return false;
}

function isWithinTypeNode(node) {
	for (let current = node.parent; current; current = current.parent) {
		if (ts.isTypeNode(current)) return true;
		if (ts.isStatement(current) || ts.isSourceFile(current)) return false;
	}
	return false;
}

function literalText(node) {
	if (node && (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node))) return node.text;
	return undefined;
}

function callKind(node) {
	if (node.expression.kind === ts.SyntaxKind.ImportKeyword) return "dynamic import";
	let expression = node.expression;
	while (ts.isParenthesizedExpression(expression)) expression = expression.expression;
	if (ts.isIdentifier(expression) && expression.text === "require") return "require";
	return undefined;
}

function unwrapExpression(node) {
	let current = node;
	while (
		ts.isParenthesizedExpression(current) ||
		ts.isAsExpression(current) ||
		ts.isSatisfiesExpression(current) ||
		ts.isTypeAssertionExpression(current) ||
		ts.isNonNullExpression(current) ||
		ts.isAwaitExpression(current)
	) {
		current = current.expression;
	}
	return current;
}

function typeReferenceSymbols(checker, node, visitSymbol) {
	if (ts.isTypeReferenceNode(node) || ts.isTypeQueryNode(node) || ts.isExpressionWithTypeArguments(node)) {
		const target = ts.isTypeReferenceNode(node)
			? node.typeName
			: ts.isTypeQueryNode(node)
				? node.exprName
				: node.expression;
		const symbol = checker.getSymbolAtLocation(target);
		if (symbol) visitSymbol(symbol);
	} else if (ts.isQualifiedName(node)) {
		const symbol = checker.getSymbolAtLocation(node.right);
		if (symbol) visitSymbol(symbol);
	}
}

// Advisory only: candidates are evidence-based hints, not proof that an export is safe
// to delete. Public entrypoint exports and types reachable from their signatures are
// protected. Categories describe the strongest remaining reference evidence. Computed
// dynamic access is reported as coverage uncertainty rather than treated as unused.
export function scanDeadExports(rootInput) {
	const root = resolve(rootInput);
	const diagnostics = [];
	const workspace = workspaceProgram(root);
	const evidenceFiles = evidenceSourceFiles(root);
	const rootNames = [...new Set([...workspace.files, ...evidenceFiles])].sort();
	const options = { ...workspace.options, allowJs: true, checkJs: false, noEmit: true };
	const resolutionCache = ts.createModuleResolutionCache(root, (file) => file, options);
	const program = ts.createProgram({ rootNames, options, oldProgram: workspace.program });
	const checker = program.getTypeChecker();
	const analysisFiles = rootNames.filter((file) => isWorkspaceFile(root, file));
	const sourceFileCache = new Map();
	const getSourceFile = (fileName) => {
		const absolute = resolve(fileName);
		if (!sourceFileCache.has(absolute)) sourceFileCache.set(absolute, program.getSourceFile(absolute));
		return sourceFileCache.get(absolute);
	};

	for (const file of analysisFiles) {
		const source = getSourceFile(file);
		if (!source) {
			diagnostics.push({ severity: "error", message: `Cannot read source file ${portablePath(root, file)}` });
			continue;
		}
		for (const diagnostic of source.parseDiagnostics ?? []) {
			const position =
				typeof diagnostic.start === "number"
					? source.getLineAndCharacterOfPosition(diagnostic.start)
					: { line: 0, character: 0 };
			diagnostics.push({
				severity: "error",
				message: `Syntax error in ${portablePath(root, file)}:${position.line + 1}:${position.character + 1}: ${flattenDiagnostic(diagnostic)}`,
			});
		}
	}

	const publicResult = publicEntrypoints(workspace, program, root, diagnostics);
	const publicSymbols = new Set();
	const seenTypes = new Set();
	const seenPublic = new Set();
	let publicUncertainty = 0;

	const resolveModuleFile = (sourceFile, specifier) => {
		if (!specifier || !sourceFile) return undefined;
		const resolved = ts.resolveModuleName(
			specifier,
			sourceFile.fileName,
			options,
			ts.sys,
			resolutionCache,
		).resolvedModule;
		const candidates = [];
		if (resolved) {
			const resolvedFile = resolve(resolved.resolvedFileName);
			candidates.push(resolvedFile);
			if (isDeclarationFile(resolvedFile)) {
				const sourceLike = resolvedFile
					.replace(/\.d\.([cm]?)ts$/i, ".$1ts")
					.replace(/\.d\.ts$/i, ".ts")
					.replace(/\.d\.([cm]?)tsx$/i, ".$1tsx");
				candidates.push(sourceLike);
			}
		}
		if (specifier.startsWith(".")) {
			const base = resolve(dirname(sourceFile.fileName), specifier);
			candidates.push(base);
			if (/\.(?:js|jsx|mjs|cjs)$/.test(base)) {
				const stem = base.replace(/\.(?:js|jsx|mjs|cjs)$/, "");
				for (const extension of [".ts", ".tsx", ".mts", ".cts"]) candidates.push(`${stem}${extension}`);
			}
			for (const extension of [".ts", ".tsx", ".mts", ".cts", ".d.ts"]) candidates.push(`${base}${extension}`);
			for (const extension of [".ts", ".tsx", ".mts", ".cts"]) candidates.push(join(base, `index${extension}`));
		}
		for (const candidate of candidates) {
			const source = getSourceFile(candidate);
			if (source) return resolve(candidate);
		}
		return undefined;
	};

	const addPublicSymbol = (symbol) => {
		const target = resolveAlias(checker, symbol);
		if (!target) return;
		if (symbol.flags & ts.SymbolFlags.Alias && !target.declarations?.length) {
			diagnostics.push({ severity: "error", message: `Cannot resolve public export ${symbol.getName()}` });
			return;
		}
		if (isModuleSymbol(target)) {
			if (seenPublic.has(target)) return;
			seenPublic.add(target);
			for (const exported of checker.getExportsOfModule(target)) addPublicSymbol(exported);
			return;
		}
		if (seenPublic.has(target)) return;
		seenPublic.add(target);
		publicSymbols.add(target);
		for (const declaration of target.declarations ?? []) {
			if (!isWorkspaceFile(root, declaration.getSourceFile().fileName)) continue;
			visitDeclarationTypes(declaration);
			const type = checker.getTypeOfSymbolAtLocation(target, declaration);
			visitType(type);
		}
	};

	const visitSignature = (signature) => {
		for (const parameter of signature.getParameters()) {
			const declaration = parameter.declarations?.[0];
			addPublicSymbol(parameter);
			if (declaration) visitType(checker.getTypeOfSymbolAtLocation(parameter, declaration));
		}
		visitType(signature.getReturnType());
		for (const parameter of signature.getTypeParameters() ?? []) {
			visitType(parameter);
		}
	};

	const visitType = (type) => {
		if (!type || seenTypes.has(type)) return;
		seenTypes.add(type);
		if (type.aliasSymbol) addPublicSymbol(type.aliasSymbol);
		if (type.symbol) addPublicSymbol(type.symbol);
		const arguments_ = type.typeArguments ?? [];
		for (const argument of arguments_) visitType(argument);
		if (type.isUnion?.() || type.isIntersection?.()) {
			for (const member of type.types) visitType(member);
		}
		if (type.flags & ts.TypeFlags.TypeParameter) {
			visitType(type.getConstraint?.());
			visitType(type.getDefault?.());
		}
		const localSymbol = type.symbol ? isWorkspaceSymbol(type.symbol, root) : false;
		if (!type.symbol || localSymbol) {
			for (const property of type.getProperties?.() ?? []) {
				addPublicSymbol(property);
				const declaration = property.declarations?.[0];
				if (declaration) visitType(checker.getTypeOfSymbolAtLocation(property, declaration));
			}
			for (const signature of type.getCallSignatures?.() ?? []) visitSignature(signature);
			for (const signature of type.getConstructSignatures?.() ?? []) visitSignature(signature);
			for (const base of type.getBaseTypes?.() ?? []) visitType(base);
			visitType(type.getStringIndexType?.());
			visitType(type.getNumberIndexType?.());
		}
	};

	const visitImportType = (node) => {
		const argument = node.argument;
		if (!ts.isLiteralTypeNode(argument)) {
			publicUncertainty++;
			return;
		}
		const specifier = literalText(argument.literal);
		if (specifier === undefined) {
			publicUncertainty++;
			return;
		}
		const source = node.getSourceFile();
		const moduleFile = resolveModuleFile(source, specifier);
		if (!moduleFile) {
			if (specifier.startsWith("."))
				diagnostics.push({
					severity: "error",
					message: `Cannot resolve public signature module ${specifier} in ${portablePath(root, source.fileName)}`,
				});
			return;
		}
		if (node.qualifier) {
			const symbol = checker.getSymbolAtLocation(node.qualifier);
			if (symbol) addPublicSymbol(symbol);
			return;
		}
		const module = getSourceFile(moduleFile);
		if (!module) return;
		for (const exported of moduleExports(checker, module)) addPublicSymbol(exported);
	};

	const visitDeclarationTypes = (declaration) => {
		const visit = (node) => {
			if (ts.isImportTypeNode(node)) {
				visitImportType(node);
				for (const child of node.getChildren()) visit(child);
				return;
			}
			if (ts.isFunctionLike(node)) {
				for (const typeParameter of node.typeParameters ?? []) visit(typeParameter);
				for (const parameter of node.parameters) visit(parameter);
				if (node.type) visit(node.type);
				return;
			}
			if (ts.isVariableDeclaration(node) || ts.isPropertyDeclaration(node) || ts.isParameter(node)) {
				if (node.type) visit(node.type);
				if (node.initializer) visitType(checker.getTypeAtLocation(node.initializer));
				return;
			}
			if (ts.isPropertyAssignment(node)) {
				visitType(checker.getTypeAtLocation(node.initializer));
				return;
			}
			if (ts.isExportAssignment(node)) {
				visitType(checker.getTypeAtLocation(node.expression));
				return;
			}
			if (ts.isTypeNode(node)) {
				typeReferenceSymbols(checker, node, addPublicSymbol);
				for (const child of node.getChildren()) visit(child);
				return;
			}
			for (const child of node.getChildren()) visit(child);
		};
		visit(declaration);
	};

	for (const file of publicResult.files) {
		const source = getSourceFile(file);
		if (!source) continue;
		const module = checker.getSymbolAtLocation(source);
		if (!module) {
			diagnostics.push({
				severity: "error",
				message: `Public entrypoint has no module symbol: ${portablePath(root, file)}`,
			});
			continue;
		}
		for (const exported of checker.getExportsOfModule(module)) addPublicSymbol(exported);
	}

	const candidates = [];
	const candidateFiles = [];
	for (const pkg of workspace.packages) {
		for (const file of pkg.files) {
			if (!isCandidateFile(root, file)) continue;
			const source = getSourceFile(file);
			if (!source) {
				diagnostics.push({ severity: "error", message: `Cannot read source file ${portablePath(root, file)}` });
				continue;
			}
			if (isGeneratedSource(source.text)) continue;
			candidateFiles.push(file);
			const module = checker.getSymbolAtLocation(source);
			if (!module) continue;
			const groups = new Map();
			for (const exported of checker.getExportsOfModule(module)) {
				const target = resolveAlias(checker, exported);
				if (!target || publicSymbols.has(target) || isModuleSymbol(target)) continue;
				if (!isLocalTopLevelDeclaration(target, source)) continue;
				if (!groups.has(target)) groups.set(target, new Set());
				groups.get(target).add(exported.getName());
			}
			for (const [target, names] of groups) {
				const sorted = [...names].sort((left, right) => left.localeCompare(right, "en"));
				const canonical = names.has(target.getName()) ? target.getName() : sorted[0];
				const declaration = (target.declarations ?? []).find(
					(candidate) => candidate.getSourceFile() === source && isTopLevelDeclaration(candidate),
				);
				if (!declaration) continue;
				const position = source.getLineAndCharacterOfPosition(declaration.getStart(source));
				candidates.push({
					file: portablePath(root, file),
					export: canonical,
					aliases: sorted.filter((name) => name !== canonical),
					category: undefined,
					line: position.line + 1,
					column: position.character + 1,
					target,
					source,
				});
			}
		}
	}

	const references = new Map();
	const globalUncertainties = [];
	const moduleUncertainties = new Map();
	const exportedTargetsCache = new Map();
	const candidateBySymbol = new Map();
	for (const candidate of candidates) candidateBySymbol.set(candidate.target, candidate);

	const exportedTargets = (source) => {
		if (!exportedTargetsCache.has(source)) {
			exportedTargetsCache.set(
				source,
				new Set(moduleExports(checker, source).map((symbol) => resolveAlias(checker, symbol))),
			);
		}
		return exportedTargetsCache.get(source);
	};

	const record = (target, source, node, kind, reexport = false) => {
		const candidate = candidateBySymbol.get(target);
		if (!candidate) return;
		const sameFile = candidate.source === source;
		const test = !sameFile && isTestLikePath(portablePath(root, source.fileName));
		let barrel = reexport;
		if (!barrel && kind === "import" && !sameFile) barrel = exportedTargets(source).has(target);
		const position = source.getLineAndCharacterOfPosition(node.getStart(source));
		const entries = references.get(candidate) ?? [];
		entries.push({
			file: portablePath(root, source.fileName),
			kind,
			sameFile,
			test,
			reexport: barrel,
			line: position.line + 1,
			column: position.character + 1,
		});
		references.set(candidate, entries);
	};

	const markModule = (moduleFile, source, node, kind, reexport = false) => {
		const module = getSourceFile(moduleFile);
		if (!module) return;
		for (const exported of moduleExports(checker, module)) {
			record(resolveAlias(checker, exported), source, node, kind, reexport);
		}
	};

	const addGlobalUncertainty = (source, node, kind) => {
		const position = source.getLineAndCharacterOfPosition(node.getStart(source));
		globalUncertainties.push({
			file: portablePath(root, source.fileName),
			line: position.line + 1,
			column: position.character + 1,
			kind,
		});
	};

	const addModuleUncertainty = (moduleFile, source, node) => {
		const module = getSourceFile(moduleFile);
		if (!module) return;
		const targets = new Set(moduleExports(checker, module).map((symbol) => resolveAlias(checker, symbol)));
		const affected = new Set(
			candidates.filter((candidate) => targets.has(candidate.target)).map((candidate) => candidate.file),
		);
		if (affected.size === 0) return;
		const position = source.getLineAndCharacterOfPosition(node.getStart(source));
		const key = `${portablePath(root, source.fileName)}\0${position.line}\0${position.character}`;
		moduleUncertainties.set(key, {
			file: portablePath(root, source.fileName),
			line: position.line + 1,
			column: position.character + 1,
			module: portablePath(root, moduleFile),
			affectedFiles: [...affected].sort(),
		});
	};

	const namespaceModule = (expression, seen = new Set()) => {
		const target = unwrapExpression(expression);
		if (seen.has(target)) return undefined;
		seen.add(target);
		if (ts.isCallExpression(target)) {
			const kind = callKind(target);
			const argument = target.arguments[0];
			if ((kind === "dynamic import" || kind === "require") && argument) {
				const specifier = literalText(argument);
				if (specifier !== undefined) return resolveModuleFile(expression.getSourceFile(), specifier);
			}
			return undefined;
		}
		if (ts.isPropertyAccessExpression(target)) {
			const file = namespaceModule(target.expression, seen);
			const source = file ? getSourceFile(file) : undefined;
			const symbol = source ? exportSymbol(source, checker, target.name.text) : undefined;
			const resolved = symbol ? resolveAlias(checker, symbol) : undefined;
			return resolved && isModuleSymbol(resolved) ? symbolSourceFile(resolved)?.fileName : undefined;
		}
		if (!ts.isIdentifier(target)) return undefined;
		const symbol = checker.getSymbolAtLocation(target);
		if (symbol) {
			const resolved = resolveAlias(checker, symbol);
			if (isModuleSymbol(resolved)) {
				const source = symbolSourceFile(resolved);
				if (source) return resolve(source.fileName);
			}
			for (const declaration of resolved.declarations ?? []) {
				if (ts.isVariableDeclaration(declaration) && declaration.initializer) {
					const module = namespaceModule(declaration.initializer, seen);
					if (module) return module;
				}
			}
		}
		return undefined;
	};

	const visit = (node) => {
		if (
			(ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) &&
			node.moduleSpecifier &&
			ts.isStringLiteralLike(node.moduleSpecifier) &&
			node.moduleSpecifier.text.startsWith(".") &&
			!resolveModuleFile(node.getSourceFile(), node.moduleSpecifier.text)
		) {
			addGlobalUncertainty(node.getSourceFile(), node, `unresolved local module ${node.moduleSpecifier.text}`);
		}
		if (ts.isCallExpression(node)) {
			const kind = callKind(node);
			if (kind) {
				const argument = node.arguments[0];
				const specifier = argument ? literalText(argument) : undefined;
				if (specifier !== undefined) {
					const moduleFile = resolveModuleFile(node.getSourceFile(), specifier);
					if (moduleFile) markModule(moduleFile, node.getSourceFile(), node, kind);
					else if (specifier.startsWith("."))
						addGlobalUncertainty(node.getSourceFile(), node, `unresolved local module ${specifier}`);
				} else if (kind === "dynamic import" || kind === "require") {
					addGlobalUncertainty(node.getSourceFile(), node, `unresolved ${kind}`);
				}
			}
		}
		if (ts.isImportTypeNode(node)) {
			const argument = node.argument;
			const specifier = ts.isLiteralTypeNode(argument) ? literalText(argument.literal) : undefined;
			if (specifier !== undefined) {
				const moduleFile = resolveModuleFile(node.getSourceFile(), specifier);
				if (moduleFile) {
					if (node.qualifier) {
						const symbol = checker.getSymbolAtLocation(node.qualifier);
						if (symbol) record(resolveAlias(checker, symbol), node.getSourceFile(), node, "import-type");
					} else {
						markModule(moduleFile, node.getSourceFile(), node, "import-type");
					}
				}
			} else {
				addGlobalUncertainty(node.getSourceFile(), node, "unresolved import type");
			}
		}
		if (ts.isExportDeclaration(node) && node.moduleSpecifier) {
			const specifier = literalText(node.moduleSpecifier);
			if (specifier !== undefined) {
				const moduleFile = resolveModuleFile(node.getSourceFile(), specifier);
				if (moduleFile && (!node.exportClause || ts.isNamespaceExport(node.exportClause))) {
					markModule(moduleFile, node.getSourceFile(), node, "reexport", true);
				}
			}
		}
		if (ts.isExportSpecifier(node)) {
			const declaration = exportDeclarationOfSpecifier(node);
			if (declaration && !declaration.moduleSpecifier) {
				const target = localExportTarget(checker, node);
				if (target && isModuleSymbol(target)) {
					const source = symbolSourceFile(target);
					if (source) {
						markModule(resolve(source.fileName), node.getSourceFile(), node, "reexport", true);
					}
				}
			}
		}
		if (ts.isExportAssignment(node)) {
			const symbol = checker.getSymbolAtLocation(node.expression);
			if (symbol) {
				const target = resolveAlias(checker, symbol);
				if (isModuleSymbol(target)) {
					const source = symbolSourceFile(target);
					if (source) {
						markModule(resolve(source.fileName), node.getSourceFile(), node, "reexport", true);
					}
				}
			}
		}
		if (ts.isElementAccessExpression(node)) {
			const argument = node.argumentExpression;
			const name = literalText(argument);
			const source = node.getSourceFile();
			if (name !== undefined) {
				const moduleFile = namespaceModule(node.expression);
				let symbol;
				if (moduleFile) {
					const module = getSourceFile(moduleFile);
					symbol = module ? exportSymbol(module, checker, name) : undefined;
				}
				if (symbol) record(resolveAlias(checker, symbol), source, node, "property");
			} else {
				const moduleFile = namespaceModule(node.expression);
				if (moduleFile) addModuleUncertainty(moduleFile, source, node);
			}
		}
		if (ts.isIdentifier(node) && !isDeclarationName(node)) {
			const parent = node.parent;
			// Only namespace properties can refer to a top-level export. Resolving
			// every ordinary object property would type-check unrelated function bodies.
			if (ts.isPropertyAccessExpression(parent) && parent.name === node) {
				const file = namespaceModule(parent.expression);
				const module = file ? getSourceFile(file) : undefined;
				const exported = module ? exportSymbol(module, checker, node.text) : undefined;
				if (exported) record(resolveAlias(checker, exported), node.getSourceFile(), node, "property");
				return;
			}
			const symbol = ts.isShorthandPropertyAssignment(parent)
				? checker.getShorthandAssignmentValueSymbol(parent)
				: checker.getSymbolAtLocation(node);
			if (symbol) {
				const target = resolveAlias(checker, symbol);
				// Passing/destructuring a namespace exposes its members indirectly. A
				// direct property access is handled precisely by its property node.
				if (
					isModuleSymbol(target) &&
					!(ts.isPropertyAccessExpression(parent) && parent.expression === node) &&
					!(ts.isElementAccessExpression(parent) && parent.expression === node) &&
					!ts.isQualifiedName(parent) &&
					!ts.isImportSpecifier(parent) &&
					!ts.isImportClause(parent)
				) {
					const module = symbolSourceFile(target);
					if (module) markModule(resolve(module.fileName), node.getSourceFile(), node, "namespace");
				}
				let kind = "reference";
				if (ts.isImportSpecifier(parent) || ts.isImportClause(parent)) kind = "import";
				else if (ts.isExportSpecifier(parent)) kind = "reexport";
				else if (ts.isPropertyAccessExpression(parent) && parent.name === node) kind = "property";
				else if (ts.isQualifiedName(parent)) kind = "property";
				else if (isWithinTypeNode(node)) kind = "type";
				record(target, node.getSourceFile(), node, kind, kind === "reexport");
			}
		}
		ts.forEachChild(node, visit);
	};

	for (const source of program.getSourceFiles()) {
		if (!isWorkspaceFile(root, source.fileName) || isDeclarationFile(source.fileName)) continue;
		visit(source);
	}

	let used = 0;
	for (const candidate of candidates) {
		const entries = references.get(candidate) ?? [];
		const external = entries.filter((entry) => !entry.sameFile);
		const production = external.filter((entry) => !entry.test && !entry.reexport);
		const tests = external.filter((entry) => entry.test);
		const barrels = external.filter((entry) => !entry.test && entry.reexport);
		const sameFile = entries.filter((entry) => entry.sameFile);
		if (production.length > 0) {
			candidate.category = "used";
			used++;
			continue;
		}
		if (tests.length > 0) candidate.category = "test-only";
		else if (barrels.length > 0) candidate.category = "barrel-only";
		else if (sameFile.length > 0) candidate.category = "same-file-only";
		else candidate.category = "zero-reference";
		const affected = moduleUncertainties
			.values()
			.some((uncertainty) => uncertainty.affectedFiles.includes(candidate.file));
		if (affected) {
			candidate.review = "computed namespace property access may reference this export";
			candidate.uncertain = true;
		} else if (globalUncertainties.length > 0) {
			candidate.uncertain = true;
		}
	}

	const reported = candidates
		.filter((candidate) => candidate.category !== "used")
		.sort(
			(left, right) =>
				left.file.localeCompare(right.file, "en") ||
				left.export.localeCompare(right.export, "en") ||
				CATEGORY_ORDER.get(left.category) - CATEGORY_ORDER.get(right.category),
		);
	const snapshotCandidates = reported
		.map((candidate) => ({ file: candidate.file, export: candidate.export, category: candidate.category }))
		.sort(
			(left, right) =>
				left.file.localeCompare(right.file, "en") ||
				left.export.localeCompare(right.export, "en") ||
				CATEGORY_ORDER.get(left.category) - CATEGORY_ORDER.get(right.category),
		);
	const uncertainties = {
		global: globalUncertainties.sort(
			(left, right) =>
				left.file.localeCompare(right.file, "en") || left.line - right.line || left.column - right.column,
		),
		modules: [...moduleUncertainties.values()].sort(
			(left, right) =>
				left.file.localeCompare(right.file, "en") || left.line - right.line || left.column - right.column,
		),
	};
	if (publicUncertainty > 0) {
		uncertainties.global.push({
			file: "<public signatures>",
			line: 0,
			column: 0,
			kind: `${publicUncertainty} unresolved import type reference(s) in public signatures`,
		});
	}

	const counts = { filesScanned: analysisFiles.length, candidateFiles: candidateFiles.length };
	for (const category of CATEGORIES)
		counts[category] = reported.filter((candidate) => candidate.category === category).length;
	return {
		root,
		version: BASELINE_VERSION,
		packages: publicResult.packages,
		publicEntrypoints: publicResult.files.size,
		candidates: reported,
		used,
		diagnostics,
		uncertainties,
		counts,
		snapshot: { version: BASELINE_VERSION, candidates: snapshotCandidates },
	};
}

function isWorkspaceSymbol(symbol, root) {
	return (symbol.declarations ?? []).some((declaration) =>
		isWorkspaceFile(root, declaration.getSourceFile().fileName),
	);
}

function candidateList(value) {
	if (Array.isArray(value)) return value;
	if (isRecord(value) && Array.isArray(value.candidates)) return value.candidates;
	return [];
}

function candidateIdentity(candidate) {
	return `${candidate.file}\0${candidate.export}\0${candidate.category}`;
}

function compareCandidates(left, right) {
	return (
		left.file.localeCompare(right.file, "en") ||
		left.export.localeCompare(right.export, "en") ||
		(CATEGORY_ORDER.get(left.category) ?? CATEGORIES.length) -
			(CATEGORY_ORDER.get(right.category) ?? CATEGORIES.length)
	);
}

export function deadExportChanges(actual, baseline) {
	const actualCandidates = candidateList(actual);
	const baselineCandidates = candidateList(baseline);
	const actualIdentities = new Set(actualCandidates.map(candidateIdentity));
	const baselineIdentities = new Set(baselineCandidates.map(candidateIdentity));
	return {
		added: actualCandidates
			.filter((candidate) => !baselineIdentities.has(candidateIdentity(candidate)))
			.sort(compareCandidates),
		removed: baselineCandidates
			.filter((candidate) => !actualIdentities.has(candidateIdentity(candidate)))
			.sort(compareCandidates),
	};
}

export function validateDeadExportBaseline(value) {
	if (!isRecord(value)) return "baseline must contain a JSON object";
	if (value.version !== BASELINE_VERSION) return `unsupported baseline version ${JSON.stringify(value.version)}`;
	if (!Array.isArray(value.candidates)) return "baseline candidates must be an array";
	const identities = new Set();
	for (const [index, candidate] of value.candidates.entries()) {
		if (!isRecord(candidate)) return `baseline candidate ${index} is not an object`;
		if (typeof candidate.file !== "string" || candidate.file.length === 0) {
			return `baseline candidate ${index} needs a non-empty file string`;
		}
		if (typeof candidate.export !== "string" || candidate.export.length === 0) {
			return `baseline candidate ${index} needs a non-empty export string`;
		}
		if (!CATEGORIES.includes(candidate.category)) {
			return `baseline candidate ${index} has an invalid category ${JSON.stringify(candidate.category)}`;
		}
		const identity = candidateIdentity(candidate);
		if (identities.has(identity))
			return `baseline contains a duplicate candidate identity: ${identity.replaceAll("\0", " ")}`;
		identities.add(identity);
	}
	return undefined;
}

function loadBaseline(root, baselinePath) {
	if (!existsSync(baselinePath)) {
		return {
			error: `Baseline ${portablePath(root, baselinePath)} is missing; run node scripts/check-dead-exports.mjs --update after reviewing candidates.`,
		};
	}
	try {
		const value = JSON.parse(readFileSync(baselinePath, "utf8"));
		const invalid = validateDeadExportBaseline(value);
		return invalid
			? { error: `Baseline ${portablePath(root, baselinePath)} is invalid: ${invalid}` }
			: { baseline: value };
	} catch (error) {
		return { error: `Baseline ${portablePath(root, baselinePath)} is not valid JSON: ${messageOf(error)}` };
	}
}

function candidateLine(candidate) {
	const suffix = candidate.uncertain ? ` [needs review${candidate.review ? `: ${candidate.review}` : ""}]` : "";
	return `${candidate.file} ${candidate.export} [${candidate.category}]${suffix}`;
}

function printUncertainties(uncertainties) {
	if (uncertainties.global.length === 0 && uncertainties.modules.length === 0) return;
	console.log("Coverage uncertainty (candidates below are not proof that an export is dead):");
	for (const uncertainty of uncertainties.global) {
		console.log(`  ${uncertainty.file}:${uncertainty.line} ${uncertainty.kind}`);
	}
	for (const uncertainty of uncertainties.modules) {
		console.log(
			`  ${uncertainty.file}:${uncertainty.line} computed namespace access may read ${uncertainty.module}; affected files: ${uncertainty.affectedFiles.join(", ")}`,
		);
	}
	if (uncertainties.global.length > 0) {
		console.log("  Global unresolved imports can reference any candidate; all candidates need manual review.");
	}
}

function runUpdate(root, result) {
	const errors = result.diagnostics.filter((diagnostic) => diagnostic.severity === "error");
	if (errors.length > 0) {
		console.error("Refusing to update the dead export baseline from an incomplete scan:");
		for (const error of errors) console.error(`  ${error.message}`);
		console.error("No files changed.");
		process.exitCode = 1;
		return;
	}
	const baselinePath = join(root, BASELINE_FILE);
	try {
		mkdirSync(dirname(baselinePath), { recursive: true });
		writeFileSync(baselinePath, `${JSON.stringify(result.snapshot, null, "\t")}\n`);
	} catch (error) {
		console.error(`Failed to write dead export baseline: ${messageOf(error)}`);
		process.exitCode = 1;
		return;
	}
	console.log(
		`Updated advisory dead export baseline (${result.snapshot.candidates.length} candidate(s)). Review the diff before committing.`,
	);
}

function runReport(root, result) {
	const errors = result.diagnostics.filter((diagnostic) => diagnostic.severity === "error");
	if (errors.length > 0) {
		console.log(`Scan incomplete: ${errors.length} error(s) prevented a complete conclusion.`);
		for (const error of errors) console.error(`  ${error.message}`);
	}
	printUncertainties(result.uncertainties);
	if (result.candidates.length > 0) {
		console.log("Dead export candidates (advisory; no source or exports were removed; manual review is required):");
		for (const category of CATEGORIES) {
			const candidates = result.candidates.filter((candidate) => candidate.category === category);
			if (candidates.length === 0) continue;
			console.log(`  ${category} (${candidates.length}):`);
			for (const candidate of candidates) console.log(`    ${candidateLine(candidate)}`);
		}
	} else if (errors.length === 0) {
		console.log("No dead export candidates detected.");
	} else {
		console.log("No definite dead export candidates were identified by the incomplete scan.");
	}
	if (errors.length > 0) {
		console.log("Incremental comparison skipped because the scan is incomplete. No files changed.");
		return;
	}
	const baselinePath = join(root, BASELINE_FILE);
	const loaded = loadBaseline(root, baselinePath);
	if (loaded.error) {
		console.error(loaded.error);
	} else {
		const changes = deadExportChanges(result.snapshot, loaded.baseline);
		const actualByIdentity = new Map(result.candidates.map((candidate) => [candidateIdentity(candidate), candidate]));
		console.log("Incremental changes since baseline:");
		if (changes.added.length === 0 && changes.removed.length === 0) {
			console.log("  No new or removed candidates.");
		} else {
			for (const candidate of changes.added) {
				console.log(
					`  New candidate: ${candidateLine(actualByIdentity.get(candidateIdentity(candidate)) ?? candidate)}`,
				);
			}
			for (const candidate of changes.removed) {
				console.log(
					`  Baseline candidate no longer reported: ${candidate.file} ${candidate.export} [${candidate.category}]`,
				);
			}
		}
	}
	const counts = result.counts;
	console.log(
		`Scanned ${counts.filesScanned} source file(s) / ${counts.candidateFiles} candidate file(s); ${result.publicEntrypoints} public entrypoint source(s); used ${result.used} export(s); reported ${result.candidates.length} candidate(s) (zero-reference ${counts["zero-reference"]}, same-file-only ${counts["same-file-only"]}, test-only ${counts["test-only"]}, barrel-only ${counts["barrel-only"]}). No files changed.`,
	);
}

function main() {
	const args = process.argv.slice(2);
	const update = args.length === 1 && args[0] === "--update";
	if (args.length > 0 && !update) {
		console.error("Usage: node scripts/check-dead-exports.mjs [--update]");
		process.exitCode = 2;
		return;
	}
	const root = resolve(process.cwd());
	let result;
	try {
		result = scanDeadExports(root);
	} catch (error) {
		console.error(`Dead export scan failed: ${messageOf(error)}`);
		console.error("Scan incomplete; no conclusion was reached. No files changed.");
		if (update) process.exitCode = 1;
		return;
	}
	try {
		if (update) runUpdate(root, result);
		else runReport(root, result);
	} catch (error) {
		console.error(`Dead export report failed: ${messageOf(error)}`);
		console.error("Scan incomplete; no conclusion was reached. No files changed.");
		if (update) process.exitCode = 1;
	}
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) main();
