import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import ts from "typescript";

export const BASELINE_VERSION = 1;
// Ignore small helpers to keep the advisory report focused on substantial copies.
export const DUPLICATE_THRESHOLD = 80;
// A nested callback that is almost the whole parent is already represented by the parent.
const NESTED_PARENT_RATIO = 0.85;

const ignoredDirectories = new Set([
	"__fixtures__",
	"__generated__",
	"__mocks__",
	"__snapshots__",
	"__specs__",
	"__tests__",
	"fixtures",
	"generated",
	"node_modules",
	"spec",
	"specs",
	"test",
	"tests",
]);
const testFilePattern = /(?:^|\.)(?:fixture|fixtures|mock|mocks|spec|stories|test)(?:\.|$)/i;
const generatedFilePattern = /(?:^|\.)generated(?:\.|$)/i;
const generatedHeaderPattern =
	/^\s*(?:\/\/|\/\*|\*).*?(?:@generated|auto-?generated|automatically generated|do not edit|generated by)/im;

const portablePath = (root, file) => relative(root, file).replaceAll("\\", "/");

function scriptKind(file) {
	return file.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS;
}

function sourceFiles(root) {
	const packages = join(root, "packages");
	if (!existsSync(packages)) {
		throw new Error(`Repository packages directory not found: ${portablePath(root, packages)}`);
	}
	const files = [];
	function visit(directory) {
		let entries;
		try {
			entries = readdirSync(directory, { withFileTypes: true });
		} catch (error) {
			throw new Error(`Cannot read source directory ${portablePath(root, directory)}: ${error.message}`);
		}
		for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name, "en"))) {
			const file = join(directory, entry.name);
			if (entry.isDirectory()) {
				if (!ignoredDirectories.has(entry.name)) visit(file);
				continue;
			}
			if (!entry.isFile() || !/\.(?:[cm]?ts|tsx)$/.test(entry.name) || /\.d\.[cm]?ts$/.test(entry.name)) continue;
			if (testFilePattern.test(entry.name) || generatedFilePattern.test(entry.name)) continue;
			files.push(file);
		}
	}
	for (const entry of readdirSync(packages, { withFileTypes: true }).sort((a, b) =>
		a.name.localeCompare(b.name, "en"),
	)) {
		if (!entry.isDirectory()) continue;
		const source = join(packages, entry.name, "src");
		if (existsSync(source)) visit(source);
	}
	return files;
}

function isFunctionWithBody(node) {
	return (
		(ts.isFunctionDeclaration(node) ||
			ts.isFunctionExpression(node) ||
			ts.isArrowFunction(node) ||
			ts.isMethodDeclaration(node) ||
			ts.isConstructorDeclaration(node) ||
			ts.isGetAccessorDeclaration(node) ||
			ts.isSetAccessorDeclaration(node)) &&
		Boolean(node.body)
	);
}

function hasModifier(node, kind) {
	return (node.modifiers ?? []).some((modifier) => modifier.kind === kind);
}

function propertyNameText(name, sourceFile) {
	if (!name) return "<anonymous>";
	if (ts.isIdentifier(name) || ts.isPrivateIdentifier(name) || ts.isStringLiteral(name) || ts.isNumericLiteral(name)) {
		return name.text;
	}
	if (ts.isComputedPropertyName(name)) return `[${name.getText(sourceFile)}]`;
	return name.getText(sourceFile);
}

function enclosingClassName(node, sourceFile) {
	for (let parent = node.parent; parent; parent = parent.parent) {
		if (ts.isClassLike(parent)) return parent.name ? parent.name.getText(sourceFile) : "<anonymous>";
	}
	return null;
}

function callableName(node, sourceFile) {
	if (ts.isConstructorDeclaration(node)) {
		return `${enclosingClassName(node, sourceFile) ?? "<anonymous>"}.constructor`;
	}
	if (node.name) {
		const name = propertyNameText(node.name, sourceFile);
		const className =
			ts.isMethodDeclaration(node) || ts.isGetAccessorDeclaration(node) || ts.isSetAccessorDeclaration(node)
				? enclosingClassName(node, sourceFile)
				: null;
		return className ? `${className}.${name}` : name;
	}
	if (ts.isFunctionDeclaration(node) && hasModifier(node, ts.SyntaxKind.DefaultKeyword)) return "default";
	let parent = node.parent;
	while (
		parent &&
		(ts.isParenthesizedExpression(parent) ||
			ts.isAsExpression(parent) ||
			ts.isSatisfiesExpression(parent) ||
			ts.isTypeAssertionExpression(parent) ||
			ts.isNonNullExpression(parent))
	) {
		parent = parent.parent;
	}
	if (parent && ts.isVariableDeclaration(parent) && ts.isIdentifier(parent.name)) return parent.name.text;
	if (parent && (ts.isPropertyAssignment(parent) || ts.isPropertyDeclaration(parent))) {
		const name = propertyNameText(parent.name, sourceFile);
		const className =
			ts.isPropertyDeclaration(parent) && ts.isClassLike(parent.parent)
				? enclosingClassName(parent, sourceFile)
				: null;
		return className ? `${className}.${name}` : name;
	}
	if (parent && ts.isExportAssignment(parent)) return "default";
	if (parent && ts.isCallExpression(parent)) return "<callback>";
	return "<anonymous>";
}

// Hash the function AST without comments, whitespace or optional punctuation. Identifier
// and literal values stay significant; template text keeps raw escapes and JSX text keeps
// its exact spacing so semantically visible text is never collapsed.
function functionFingerprint(sourceFile, root) {
	const hash = createHash("sha256");
	let tokens = 0;
	function emit(value) {
		hash.update(value);
		hash.update("\0");
	}
	function visit(node, hashed = true) {
		// The callable's own name is not implementation: renamed copies stay comparable.
		// Nested names, parameter names, modifiers and type/default semantics remain significant.
		// It still counts toward the size threshold so ignoring it does not shrink candidates.
		if (root.name && node === root.name) hashed = false;
		if (ts.isJSDoc(node) || ts.isJSDocTag(node)) return;
		const children = node.getChildren(sourceFile);
		if (children.length === 0) {
			const text = node.getText(sourceFile);
			if (text.length === 0) return;
			// Statement terminators and list-separating commas are optional syntax. A comma
			// operator is still significant because it changes the expression node.
			if (node.kind === ts.SyntaxKind.SemicolonToken && node.parent?.kind !== ts.SyntaxKind.ForStatement) return;
			if (node.kind === ts.SyntaxKind.CommaToken && node.parent?.kind !== ts.SyntaxKind.BinaryExpression) return;
			let prefix = "token";
			let value;
			if (ts.isIdentifier(node) || ts.isPrivateIdentifier(node)) {
				prefix = "identifier";
				value = node.text;
			} else if (ts.isStringLiteral(node)) {
				prefix = "string";
				value = JSON.stringify(node.text);
			} else if (ts.isNumericLiteral(node) || ts.isBigIntLiteral(node)) {
				prefix = "number";
				value = node.text;
			} else if (ts.isRegularExpressionLiteral(node)) {
				prefix = "regexp";
				value = node.text;
			} else if (
				ts.isNoSubstitutionTemplateLiteral(node) ||
				node.kind === ts.SyntaxKind.TemplateHead ||
				node.kind === ts.SyntaxKind.TemplateMiddle ||
				node.kind === ts.SyntaxKind.TemplateTail
			) {
				// Raw text matters for tagged templates such as String.raw, where `\n`
				// and an actual newline are different inputs.
				prefix = "template";
				value = JSON.stringify(node.getText(sourceFile));
			} else if (ts.isJsxText(node)) {
				prefix = "jsx";
				value = JSON.stringify(node.text);
			} else {
				value = ts.tokenToString(node.kind) ?? ts.SyntaxKind[node.kind];
			}
			tokens++;
			if (hashed) emit(`${prefix}:${value}`);
			return;
		}
		if (hashed) emit(`(${ts.SyntaxKind[node.kind]}`);
		for (const child of children) visit(child, hashed);
		if (hashed) emit(")");
	}
	visit(root);
	return { hash: hash.digest("hex"), tokens };
}

function lineOf(sourceFile, position) {
	return sourceFile.getLineAndCharacterOfPosition(position).line + 1;
}

function isGeneratedSource(text) {
	return generatedHeaderPattern.test(text.slice(0, 2000));
}

function instanceLocation(instance) {
	return {
		file: instance.file,
		symbol: instance.symbol,
		line: instance.line,
		endLine: instance.endLine,
	};
}

function compareInstances(a, b) {
	return (
		a.file.localeCompare(b.file, "en") ||
		a.symbol.localeCompare(b.symbol, "en") ||
		a.line - b.line ||
		a.endLine - b.endLine
	);
}

function compareLocations(a, b) {
	return a.file.localeCompare(b.file, "en") || a.symbol.localeCompare(b.symbol, "en");
}

// Only function-like nodes with bodies are candidates. Nested duplicates are suppressed
// when the parent already represents the same exported/reportable body, avoiding one
// finding per callback in a duplicated implementation.
export function duplicateSnapshot(root) {
	root = resolve(root);
	const files = sourceFiles(root);
	const functions = [];
	let filesScanned = 0;
	let functionsScanned = 0;
	for (const file of files) {
		const text = readFileSync(file, "utf8");
		if (isGeneratedSource(text)) continue;
		filesScanned++;
		const sourceFile = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, scriptKind(file));
		const diagnostics = sourceFile.parseDiagnostics ?? [];
		if (diagnostics.length) {
			const message = diagnostics
				.map((diagnostic) => ts.flattenDiagnosticMessageText(diagnostic.messageText, "\n"))
				.join("; ");
			throw new Error(`Failed to parse ${portablePath(root, file)}: ${message}`);
		}
		const stack = [];
		function visit(node) {
			if (isFunctionWithBody(node)) {
				functionsScanned++;
				const fingerprint = functionFingerprint(sourceFile, node);
				if (fingerprint.tokens >= DUPLICATE_THRESHOLD) {
					const index = functions.length;
					functions.push({
						file: portablePath(root, file),
						symbol: callableName(node, sourceFile),
						line: lineOf(sourceFile, node.getStart(sourceFile)),
						endLine: lineOf(sourceFile, node.end),
						tokens: fingerprint.tokens,
						hash: fingerprint.hash,
						parent: stack.length ? stack[stack.length - 1] : -1,
					});
					stack.push(index);
					for (const child of node.getChildren(sourceFile)) visit(child);
					stack.pop();
					return;
				}
			}
			for (const child of node.getChildren(sourceFile)) visit(child);
		}
		visit(sourceFile);
	}

	const nearParentSuppressed = new Set();
	for (const [index, fn] of functions.entries()) {
		if (fn.parent >= 0 && fn.tokens >= functions[fn.parent].tokens * NESTED_PARENT_RATIO) {
			nearParentSuppressed.add(index);
		}
	}
	const groups = new Map();
	for (const [index, fn] of functions.entries()) {
		if (nearParentSuppressed.has(index)) continue;
		if (!groups.has(fn.hash)) groups.set(fn.hash, []);
		groups.get(fn.hash).push(index);
	}
	const duplicateHashes = new Set([...groups].filter(([, indices]) => indices.length > 1).map(([hash]) => hash));

	const nestedSuppressed = new Set(nearParentSuppressed);
	for (const [index, fn] of functions.entries()) {
		if (nearParentSuppressed.has(index)) continue;
		for (let parent = fn.parent; parent >= 0; parent = functions[parent].parent) {
			if (duplicateHashes.has(functions[parent].hash)) {
				nestedSuppressed.add(index);
				break;
			}
		}
	}

	const candidates = [];
	const clusters = [];
	for (const [index, fn] of functions.entries()) {
		if (nestedSuppressed.has(index)) continue;
		candidates.push({
			file: fn.file,
			symbol: fn.symbol,
			line: fn.line,
			endLine: fn.endLine,
			tokens: fn.tokens,
			hash: fn.hash,
		});
	}
	candidates.sort(compareInstances);
	for (const [hash, indices] of [...groups].sort(([a], [b]) => a.localeCompare(b, "en"))) {
		const members = indices.filter((index) => !nestedSuppressed.has(index)).map((index) => functions[index]);
		if (members.length < 2) continue;
		const occurrences = members.map(instanceLocation).sort(compareInstances);
		clusters.push({ hash, tokens: members[0].tokens, occurrences });
	}
	clusters.sort((a, b) => a.hash.localeCompare(b.hash, "en"));
	return {
		version: BASELINE_VERSION,
		threshold: DUPLICATE_THRESHOLD,
		filesScanned,
		functionsScanned,
		eligibleFunctions: functions.length,
		suppressedNested: nestedSuppressed.size,
		candidates,
		clusters,
		duplicateInstances: clusters.reduce((total, cluster) => total + cluster.occurrences.length, 0),
	};
}

// Baseline identities deliberately omit lines: { hash, file, symbol, count } lets code move
// without churn, while an added copy in an existing file/cluster increases the count.
export function baselineFromSnapshot(snapshot) {
	const clusters = snapshot.clusters.map((cluster) => {
		const occurrences = new Map();
		for (const occurrence of cluster.occurrences) {
			const key = JSON.stringify([occurrence.file, occurrence.symbol]);
			if (!occurrences.has(key)) {
				occurrences.set(key, { file: occurrence.file, symbol: occurrence.symbol, count: 0 });
			}
			occurrences.get(key).count++;
		}
		return {
			hash: cluster.hash,
			tokens: cluster.tokens,
			occurrences: [...occurrences.values()].sort(
				(a, b) => a.file.localeCompare(b.file, "en") || a.symbol.localeCompare(b.symbol, "en"),
			),
		};
	});
	clusters.sort((a, b) => a.hash.localeCompare(b.hash, "en"));
	return { version: BASELINE_VERSION, threshold: DUPLICATE_THRESHOLD, clusters };
}

function actualGroups(clusters) {
	const groups = new Map();
	for (const cluster of clusters) {
		for (const occurrence of cluster.occurrences) {
			const key = JSON.stringify([cluster.hash, occurrence.file, occurrence.symbol]);
			if (!groups.has(key)) {
				groups.set(key, {
					hash: cluster.hash,
					tokens: cluster.tokens,
					file: occurrence.file,
					symbol: occurrence.symbol,
					instances: [],
				});
			}
			groups.get(key).instances.push(occurrence);
		}
	}
	for (const group of groups.values()) group.instances.sort(compareInstances);
	return groups;
}

function baselineGroups(clusters) {
	const groups = new Map();
	for (const cluster of clusters) {
		for (const occurrence of cluster.occurrences) {
			groups.set(JSON.stringify([cluster.hash, occurrence.file, occurrence.symbol]), {
				hash: cluster.hash,
				tokens: cluster.tokens,
				file: occurrence.file,
				symbol: occurrence.symbol,
				count: occurrence.count,
			});
		}
	}
	return groups;
}

export function duplicateChanges(actual, baseline) {
	const actualByLocation = actualGroups(actual.clusters);
	const baselineByLocation = baselineGroups(baseline.clusters);
	const baselineHashes = new Set(baseline.clusters.map((cluster) => cluster.hash));
	const added = [];
	const addedGroups = [];
	for (const [key, group] of [...actualByLocation].sort(([a], [b]) => a.localeCompare(b, "en"))) {
		const allowed = baselineByLocation.get(key)?.count ?? 0;
		if (group.instances.length <= allowed) continue;
		const extra = group.instances.slice(allowed);
		added.push(
			...extra.map((instance) => ({
				hash: group.hash,
				tokens: group.tokens,
				file: group.file,
				symbol: group.symbol,
				line: instance.line,
				endLine: instance.endLine,
			})),
		);
		addedGroups.push({
			hash: group.hash,
			tokens: group.tokens,
			file: group.file,
			symbol: group.symbol,
			baselineCount: allowed,
			actualCount: group.instances.length,
			addedCount: group.instances.length - allowed,
			newCluster: !baselineHashes.has(group.hash),
			instances: group.instances.map(instanceLocation),
		});
	}
	added.sort(compareInstances);
	const removed = [];
	for (const [key, group] of [...baselineByLocation].sort(([a], [b]) => a.localeCompare(b, "en"))) {
		const count = actualByLocation.get(key)?.instances.length ?? 0;
		if (count >= group.count) continue;
		removed.push({
			hash: group.hash,
			tokens: group.tokens,
			file: group.file,
			symbol: group.symbol,
			baselineCount: group.count,
			actualCount: count,
			removedCount: group.count - count,
		});
	}
	removed.sort(compareLocations);
	return {
		added,
		addedGroups,
		removed,
		newClusters: new Set(addedGroups.filter((group) => group.newCluster).map((group) => group.hash)).size,
		removedCount: removed.reduce((total, group) => total + group.removedCount, 0),
	};
}

function baselineInstanceCount(baseline) {
	return baseline.clusters.reduce(
		(total, cluster) => total + cluster.occurrences.reduce((count, occurrence) => count + occurrence.count, 0),
		0,
	);
}

function report(snapshot, baseline, changes) {
	const lines = [];
	if (changes.added.length === 0) {
		lines.push("No new duplicate implementation instances.");
	} else {
		lines.push(
			`New duplicate implementation instances: ${changes.added.length} (${changes.newClusters} new cluster(s)).`,
		);
		const clustersByHash = new Map(snapshot.clusters.map((cluster) => [cluster.hash, cluster]));
		for (const group of changes.addedGroups) {
			const cluster = group.newCluster ? "new cluster" : "existing cluster";
			lines.push(
				`  ${group.file} ${group.symbol} (+${group.addedCount}, ${group.actualCount} now; ${group.hash.slice(0, 12)}; ${group.tokens} tokens; ${cluster})`,
			);
			// Include existing counterparts so a new copy can be reviewed from the report.
			for (const instance of clustersByHash.get(group.hash).occurrences) {
				lines.push(`    ${instance.file}:${instance.line} ${instance.symbol}`);
			}
		}
	}
	if (changes.removedCount > 0) {
		lines.push(
			`Baseline occurrences no longer present: ${changes.removedCount}. Review and run --update to prune them.`,
		);
	}
	lines.push(
		`Scanned ${snapshot.filesScanned} files / ${snapshot.functionsScanned} functions; ${snapshot.eligibleFunctions} significant (>= ${snapshot.threshold} tokens); ${snapshot.clusters.length} duplicate clusters / ${snapshot.duplicateInstances} instances.`,
	);
	lines.push(`Baseline: ${baseline.clusters.length} clusters / ${baselineInstanceCount(baseline)} instances.`);
	return lines.join("\n");
}

function baselinePath(root) {
	return join(root, "scripts/baselines/duplicates.json");
}

function validateBaseline(baseline) {
	if (!baseline || typeof baseline !== "object" || !Array.isArray(baseline.clusters)) {
		return "baseline has no clusters array";
	}
	if (baseline.version !== BASELINE_VERSION) {
		return `unsupported baseline version ${JSON.stringify(baseline.version)} (expected ${BASELINE_VERSION})`;
	}
	if (baseline.threshold !== DUPLICATE_THRESHOLD) {
		return `baseline threshold ${JSON.stringify(baseline.threshold)} does not match ${DUPLICATE_THRESHOLD}`;
	}
	for (const [clusterIndex, cluster] of baseline.clusters.entries()) {
		if (!cluster || typeof cluster !== "object") return `baseline cluster ${clusterIndex} is not an object`;
		if (typeof cluster.hash !== "string" || cluster.hash.length === 0) {
			return `baseline cluster ${clusterIndex} has an invalid hash`;
		}
		if (!Number.isInteger(cluster.tokens) || cluster.tokens < 0) {
			return `baseline cluster ${clusterIndex} has an invalid token count`;
		}
		if (!Array.isArray(cluster.occurrences)) {
			return `baseline cluster ${clusterIndex} has no occurrences array`;
		}
		for (const [occurrenceIndex, occurrence] of cluster.occurrences.entries()) {
			if (!occurrence || typeof occurrence !== "object") {
				return `baseline cluster ${clusterIndex} occurrence ${occurrenceIndex} is not an object`;
			}
			if (typeof occurrence.file !== "string" || occurrence.file.length === 0) {
				return `baseline cluster ${clusterIndex} occurrence ${occurrenceIndex} has an invalid file`;
			}
			if (typeof occurrence.symbol !== "string" || occurrence.symbol.length === 0) {
				return `baseline cluster ${clusterIndex} occurrence ${occurrenceIndex} has an invalid symbol`;
			}
			if (!Number.isInteger(occurrence.count) || occurrence.count < 1) {
				return `baseline cluster ${clusterIndex} occurrence ${occurrenceIndex} has an invalid count`;
			}
		}
	}
	return null;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
	const root = process.cwd();
	const args = process.argv.slice(2);
	const update = args[0] === "--update";
	if (args.length > 1 || (args.length === 1 && !update)) {
		console.error("Usage: node scripts/check-duplicates.mjs [--update]");
		process.exitCode = 1;
	} else {
		let snapshot;
		try {
			snapshot = duplicateSnapshot(root);
		} catch (error) {
			console.error(`Duplicate scan failed: ${error instanceof Error ? error.message : String(error)}`);
			console.error("Duplicate check is advisory and did not modify the baseline.");
			if (update) process.exitCode = 1;
		}
		if (snapshot) {
			if (update) {
				const baseline = baselineFromSnapshot(snapshot);
				const destination = baselinePath(root);
				try {
					mkdirSync(dirname(destination), { recursive: true });
					writeFileSync(destination, `${JSON.stringify(baseline, null, "\t")}\n`);
				} catch (error) {
					console.error(
						`Failed to write duplicate baseline: ${error instanceof Error ? error.message : String(error)}`,
					);
					process.exitCode = 1;
				}
				if (!process.exitCode) {
					console.log(
						`Updated duplicate implementation baseline (${baseline.clusters.length} clusters); review the diff before committing.`,
					);
				}
			} else {
				const destination = baselinePath(root);
				let baseline;
				let problem;
				try {
					baseline = JSON.parse(readFileSync(destination, "utf8"));
					problem = validateBaseline(baseline);
				} catch (error) {
					problem =
						error?.code === "ENOENT"
							? `baseline is missing at ${portablePath(root, destination)}`
							: `baseline is unreadable: ${error instanceof Error ? error.message : String(error)}`;
				}
				if (problem) {
					console.error(`Duplicate scan could not compare: ${problem}.`);
					console.error("Duplicate check is advisory; no baseline was written. Run --update to create it.");
				} else {
					try {
						console.log(report(snapshot, baseline, duplicateChanges(snapshot, baseline)));
					} catch (error) {
						console.error(
							`Duplicate scan could not compare: baseline is malformed: ${error instanceof Error ? error.message : String(error)}.`,
						);
						console.error("Duplicate check is advisory; no baseline was written. Run --update to refresh it.");
					}
				}
			}
		}
	}
}
