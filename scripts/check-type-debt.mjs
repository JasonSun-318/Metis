import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, join, posix, relative, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import ts from "typescript";

const BASELINE_VERSION = 1;
const BASELINE_FILE = "scripts/baselines/type-debt.json";
const SCANNABLE_EXTENSION = /\.(?:[cm]?ts|tsx)$/i;
const DECLARATION_EXTENSION = /\.d\.[cm]?ts$/i;
const CATEGORIES = ["explicit-any", "as-any", "non-null-assertion"];
const CATEGORY_ORDER = new Map(CATEGORIES.map((category, index) => [category, index]));
const SUPPRESSION_PREFIX = "suppression:";
const SUPPRESSION_CATEGORY = /^(?:lint|assist|format)(?:\/[A-Za-z0-9][A-Za-z0-9_-]*)*$/;

const IGNORED_DIRECTORIES = new Set([
	".artifacts",
	".cache",
	".claude",
	".codegraph",
	".cursor",
	".devin",
	".git",
	".next",
	".nyc_output",
	".turbo",
	".vite",
	".webpack",
	"artifacts",
	"build",
	"coverage",
	"dist",
	"docs",
	"logs",
	"node_modules",
	"out",
	"plans",
	"playwright-report",
	"reports",
	"test-results",
]);
const TEST_SEGMENTS = new Set([
	"__e2e__",
	"__fixtures__",
	"__mocks__",
	"__snapshots__",
	"__specs__",
	"__tests__",
	"e2e",
	"fixture",
	"fixtures",
	"mock",
	"mocks",
	"snapshots",
	"spec",
	"specs",
	"test",
	"test-support",
	"tests",
]);
const TEST_FILE_PATTERN = /(?:^|\.)(?:e2e|fixture|fixtures|mock|mocks|spec|stories|test)(?:\.|$)/i;
const GENERATED_FILE_PATTERN = /(?:^|\.)generated(?:\.|$)/i;
const GENERATED_HEADER_PATTERN =
	/^\s*(?:\/\/|\/\*|\*).*?(?:@generated|auto-?generated|automatically generated|do not edit|generated by)/im;

function messageOf(error) {
	return error instanceof Error ? error.message : String(error);
}

function isRecord(value) {
	return value !== null && typeof value === "object" && !Array.isArray(value);
}

function compareText(left, right) {
	return left.localeCompare(right, "en");
}

function flattenDiagnostic(diagnostic) {
	return ts.flattenDiagnosticMessageText(diagnostic.messageText, "\n");
}

function categoryRank(category) {
	if (CATEGORY_ORDER.has(category)) return CATEGORY_ORDER.get(category);
	return CATEGORIES.length + 1;
}

function categoryKey(category) {
	if (CATEGORIES.includes(category)) return category;
	if (!category.startsWith(SUPPRESSION_PREFIX)) return undefined;
	return SUPPRESSION_CATEGORY.test(category.slice(SUPPRESSION_PREFIX.length)) ? category : undefined;
}

function compareCounts(left, right) {
	return (
		compareText(left.file, right.file) ||
		categoryRank(left.category) - categoryRank(right.category) ||
		compareText(left.category, right.category)
	);
}

function countIdentity(count) {
	return `${count.file}\0${count.category}`;
}

function isTestLikePath(relativePath) {
	const segments = relativePath.split("/");
	if (segments.some((segment) => TEST_SEGMENTS.has(segment.toLowerCase()))) return true;
	const base = segments[segments.length - 1] ?? "";
	return TEST_FILE_PATTERN.test(base);
}

function isGeneratedPath(relativePath) {
	const segments = relativePath.split("/");
	if (segments.some((segment) => segment === "generated" || segment === "__generated__")) return true;
	const base = segments[segments.length - 1] ?? "";
	return GENERATED_FILE_PATTERN.test(base);
}

function isGeneratedSource(text) {
	const scanner = ts.createScanner(ts.ScriptTarget.Latest, false, ts.LanguageVariant.Standard, text.slice(0, 2000));
	for (let token = scanner.scan(); token !== ts.SyntaxKind.EndOfFileToken; token = scanner.scan()) {
		if (token === ts.SyntaxKind.SingleLineCommentTrivia || token === ts.SyntaxKind.MultiLineCommentTrivia) {
			if (GENERATED_HEADER_PATTERN.test(scanner.getTokenText())) return true;
		} else if (
			token !== ts.SyntaxKind.WhitespaceTrivia &&
			token !== ts.SyntaxKind.NewLineTrivia &&
			token !== ts.SyntaxKind.ShebangTrivia
		) {
			break;
		}
	}
	return false;
}

function statPath(path) {
	try {
		const stats = statSync(path);
		return { exists: true, directory: stats.isDirectory() };
	} catch (error) {
		if (error && typeof error === "object" && "code" in error && error.code === "ENOENT") {
			return { exists: false, directory: false };
		}
		return { exists: false, directory: false, error };
	}
}

function sourceFiles(root, diagnostics) {
	const files = [];
	const packagesDirectory = join(root, "packages");
	let packages;
	try {
		packages = readdirSync(packagesDirectory, { withFileTypes: true });
	} catch (error) {
		diagnostics.push({
			severity: "error",
			message: `Cannot read packages directory packages: ${messageOf(error)}`,
		});
		return files;
	}
	for (const entry of packages.sort((left, right) => compareText(left.name, right.name))) {
		if (!entry.isDirectory()) continue;
		const sourceDirectory = join(packagesDirectory, entry.name, "src");
		const status = statPath(sourceDirectory);
		if (status.error) {
			diagnostics.push({
				severity: "error",
				message: `Cannot access source path ${portable(root, sourceDirectory)}: ${messageOf(status.error)}`,
			});
			continue;
		}
		if (!status.exists) continue;
		if (!status.directory) {
			diagnostics.push({
				severity: "error",
				message: `Source path ${portable(root, sourceDirectory)} is not a directory`,
			});
			continue;
		}
		walkSourceDirectory(root, sourceDirectory, files, diagnostics);
	}
	return files;
}

function walkSourceDirectory(root, directory, files, diagnostics) {
	let entries;
	try {
		entries = readdirSync(directory, { withFileTypes: true }).sort((left, right) =>
			compareText(left.name, right.name),
		);
	} catch (error) {
		diagnostics.push({
			severity: "error",
			message: `Cannot read source directory ${portable(root, directory)}: ${messageOf(error)}`,
		});
		return;
	}
	for (const entry of entries) {
		const absolute = join(directory, entry.name);
		const relativePath = portable(root, absolute);
		if (entry.isDirectory()) {
			if (entry.name.startsWith(".") || IGNORED_DIRECTORIES.has(entry.name)) continue;
			if (isTestLikePath(relativePath) || isGeneratedPath(relativePath)) continue;
			walkSourceDirectory(root, absolute, files, diagnostics);
			continue;
		}
		if (!entry.isFile()) continue;
		if (!SCANNABLE_EXTENSION.test(entry.name) || DECLARATION_EXTENSION.test(entry.name)) continue;
		if (isTestLikePath(relativePath) || isGeneratedPath(relativePath)) continue;
		files.push({ absolute, relativePath });
	}
}

function portable(root, fileName) {
	return relative(root, resolve(fileName)).replaceAll("\\", "/") || ".";
}

function scriptKindFor(relativePath) {
	return /\.tsx$/i.test(relativePath) ? ts.ScriptKind.TSX : ts.ScriptKind.TS;
}

function isRawTextNode(node) {
	return (
		node.kind === ts.SyntaxKind.JsxText ||
		node.kind === ts.SyntaxKind.TemplateHead ||
		node.kind === ts.SyntaxKind.TemplateMiddle ||
		node.kind === ts.SyntaxKind.TemplateTail ||
		node.kind === ts.SyntaxKind.NoSubstitutionTemplateLiteral ||
		node.kind === ts.SyntaxKind.RegularExpressionLiteral ||
		ts.isStringLiteralLike(node)
	);
}

function collectComments(text, sourceFile) {
	const candidates = [];
	const rawRanges = [];
	const seen = new Set();
	const walk = (node) => {
		if (isRawTextNode(node)) {
			rawRanges.push({ pos: node.getStart(sourceFile), end: node.end });
		}
		for (const range of ts.getLeadingCommentRanges(text, node.pos) ?? []) {
			const key = `${range.pos}:${range.end}`;
			if (seen.has(key)) continue;
			seen.add(key);
			candidates.push(range);
		}
		for (const range of ts.getTrailingCommentRanges(text, node.end) ?? []) {
			const key = `${range.pos}:${range.end}`;
			if (seen.has(key)) continue;
			seen.add(key);
			candidates.push(range);
		}
		for (const child of node.getChildren(sourceFile)) walk(child);
	};
	walk(sourceFile);
	return candidates.filter((range) => !rawRanges.some((raw) => range.pos >= raw.pos && range.pos < raw.end));
}

function suppressionCategories(commentText) {
	const isBlock = commentText.startsWith("/*");
	let body;
	if (isBlock) {
		body = commentText.endsWith("*/") ? commentText.slice(2, -2) : commentText.slice(2);
	} else if (commentText.startsWith("//")) {
		body = commentText.slice(2);
	} else {
		return [];
	}
	const categories = [];
	for (const line of body.split(/\r?\n/u)) {
		let content = line.replace(/^\s+/u, "");
		if (isBlock) content = content.replace(/^\*\s*/u, "");
		const match = /^biome-(ignore(?:-all|-start)?)(?=\s|$)(.*)$/su.exec(content);
		if (!match) continue;
		const rest = match[2].trim();
		if (rest.length === 0) continue;
		const colon = rest.indexOf(":");
		const head = colon >= 0 ? rest.slice(0, colon) : rest;
		const tokens = head.split(/[\s,]+/u).filter(Boolean);
		const lineCategories = new Set();
		let valid = tokens.length > 0;
		for (const token of tokens) {
			const category = token.split("(")[0];
			if (!category || !SUPPRESSION_CATEGORY.test(category)) {
				valid = false;
				break;
			}
			lineCategories.add(category);
		}
		if (valid) categories.push(...lineCategories);
	}
	return categories;
}

function emptyFileCounts() {
	return new Map();
}

function increment(counts, category, amount = 1) {
	counts.set(category, (counts.get(category) ?? 0) + amount);
}

function scanSourceText(relativePath, text) {
	const sourceFile = ts.createSourceFile(
		relativePath,
		text,
		ts.ScriptTarget.Latest,
		true,
		scriptKindFor(relativePath),
	);
	const diagnostics = (sourceFile.parseDiagnostics ?? []).map((diagnostic) => {
		const position =
			typeof diagnostic.start === "number"
				? sourceFile.getLineAndCharacterOfPosition(diagnostic.start)
				: { line: 0, character: 0 };
		return {
			severity: "error",
			message: `Syntax error in ${relativePath}:${position.line + 1}:${position.character + 1}: ${flattenDiagnostic(diagnostic)}`,
		};
	});
	const counts = emptyFileCounts();
	const visit = (node) => {
		if (node.kind === ts.SyntaxKind.AnyKeyword) increment(counts, "explicit-any");
		if (ts.isAsExpression(node) || ts.isTypeAssertionExpression(node)) {
			let assertedType = node.type;
			while (ts.isParenthesizedTypeNode(assertedType)) assertedType = assertedType.type;
			if (assertedType.kind === ts.SyntaxKind.AnyKeyword) increment(counts, "as-any");
		}
		if (ts.isNonNullExpression(node)) increment(counts, "non-null-assertion");
		ts.forEachChild(node, visit);
	};
	visit(sourceFile);
	for (const comment of collectComments(text, sourceFile)) {
		for (const category of suppressionCategories(text.slice(comment.pos, comment.end))) {
			increment(counts, `${SUPPRESSION_PREFIX}${category}`);
		}
	}
	return { counts, diagnostics };
}

export function scanTypeDebt(rootInput, options = {}) {
	const root = resolve(rootInput);
	const readFile = options.readFile ?? readFileSync;
	const diagnostics = [];
	const counts = [];
	let filesScanned = 0;
	const files = sourceFiles(root, diagnostics);
	for (const file of files) {
		let text;
		try {
			text = readFile(file.absolute, "utf8");
		} catch (error) {
			diagnostics.push({
				severity: "error",
				message: `Cannot read source file ${file.relativePath}: ${messageOf(error)}`,
			});
			continue;
		}
		if (typeof text !== "string") {
			diagnostics.push({
				severity: "error",
				message: `Cannot read source file ${file.relativePath}: reader did not return text`,
			});
			continue;
		}
		if (isGeneratedSource(text)) continue;
		filesScanned++;
		let scan;
		try {
			scan = scanSourceText(file.relativePath, text);
		} catch (error) {
			diagnostics.push({
				severity: "error",
				message: `Cannot parse source file ${file.relativePath}: ${messageOf(error)}`,
			});
			continue;
		}
		diagnostics.push(...scan.diagnostics);
		for (const [category, count] of scan.counts) {
			if (count > 0) counts.push({ file: file.relativePath, category, count });
		}
	}
	counts.sort(compareCounts);
	const snapshot = { version: BASELINE_VERSION, counts };
	return {
		root,
		version: BASELINE_VERSION,
		filesScanned,
		counts,
		diagnostics,
		incomplete: diagnostics.some((diagnostic) => diagnostic.severity === "error"),
		snapshot,
	};
}

function countList(value) {
	if (Array.isArray(value)) return value;
	if (isRecord(value) && Array.isArray(value.counts)) return value.counts;
	return [];
}

function isSafeRelativePath(file) {
	if (typeof file !== "string" || file.length === 0) return false;
	if (file.includes("\\") || /[\u0000-\u001f]/u.test(file)) return false;
	if (isAbsolute(file) || /^[A-Za-z]:/.test(file)) return false;
	const segments = file.split("/");
	if (segments.some((segment) => segment === "" || segment === "." || segment === "..")) return false;
	return posix.normalize(file) === file;
}

export function typeDebtChanges(actual, baseline) {
	const actualCounts = countList(actual);
	const baselineCounts = countList(baseline);
	const actualByKey = new Map(actualCounts.map((count) => [countIdentity(count), count]));
	const baselineByKey = new Map(baselineCounts.map((count) => [countIdentity(count), count]));
	const added = [];
	const removed = [];
	for (const [key, count] of actualByKey) {
		const previous = baselineByKey.get(key)?.count ?? 0;
		if (count.count > previous) {
			added.push({
				file: count.file,
				category: count.category,
				delta: count.count - previous,
				previous,
				count: count.count,
			});
		}
	}
	for (const [key, count] of baselineByKey) {
		const current = actualByKey.get(key)?.count ?? 0;
		if (current < count.count) {
			removed.push({
				file: count.file,
				category: count.category,
				delta: count.count - current,
				previous: count.count,
				count: current,
			});
		}
	}
	added.sort(compareCounts);
	removed.sort(compareCounts);
	return { added, removed };
}

export function validateTypeDebtBaseline(value) {
	if (!isRecord(value)) return "baseline must contain a JSON object";
	if (value.version !== BASELINE_VERSION) return `unsupported baseline version ${JSON.stringify(value.version)}`;
	if (!Array.isArray(value.counts)) return "baseline counts must be an array";
	const identities = new Set();
	for (const [index, count] of value.counts.entries()) {
		if (!isRecord(count)) return `baseline count ${index} is not an object`;
		if (!isSafeRelativePath(count.file)) {
			return `baseline count ${index} has an unsafe or non-relative file path ${JSON.stringify(count.file)}`;
		}
		if (typeof count.category !== "string" || categoryKey(count.category) === undefined) {
			return `baseline count ${index} has an invalid category ${JSON.stringify(count.category)}`;
		}
		if (
			typeof count.count !== "number" ||
			!Number.isFinite(count.count) ||
			!Number.isInteger(count.count) ||
			count.count < 0
		) {
			return `baseline count ${index} needs a finite non-negative integer count`;
		}
		const identity = countIdentity(count);
		if (identities.has(identity)) {
			return `baseline contains a duplicate file/category key: ${count.file} ${count.category}`;
		}
		identities.add(identity);
	}
	return undefined;
}

function loadBaseline(baselinePath, displayPath) {
	if (!existsSync(baselinePath)) {
		return {
			error: `Baseline ${displayPath} is missing; run node scripts/check-type-debt.mjs --update after reviewing counts.`,
		};
	}
	try {
		const value = JSON.parse(readFileSync(baselinePath, "utf8"));
		const invalid = validateTypeDebtBaseline(value);
		return invalid ? { error: `Baseline ${displayPath} is invalid: ${invalid}` } : { baseline: value };
	} catch (error) {
		return { error: `Baseline ${displayPath} is not valid JSON: ${messageOf(error)}` };
	}
}

function displayPath(root, baselinePath) {
	const relative = portable(root, baselinePath);
	return relative.startsWith("../") || relative === ".." ? baselinePath : relative;
}

function countTotals(counts) {
	const totals = new Map(CATEGORIES.map((category) => [category, 0]));
	const suppressions = new Map();
	let suppressionTotal = 0;
	for (const count of counts) {
		if (count.category.startsWith(SUPPRESSION_PREFIX)) {
			const rule = count.category.slice(SUPPRESSION_PREFIX.length);
			suppressions.set(rule, (suppressions.get(rule) ?? 0) + count.count);
			suppressionTotal += count.count;
		} else {
			totals.set(count.category, (totals.get(count.category) ?? 0) + count.count);
		}
	}
	return {
		totals,
		suppressions,
		suppressionTotal,
		filesWithCounts: new Set(counts.map((count) => count.file)).size,
	};
}

function printTotals(result) {
	if (result.counts.length === 0) {
		console.log(
			result.incomplete
				? "No type debt counts were produced before the scan became incomplete."
				: "No type debt was counted.",
		);
		return;
	}
	const { totals, suppressions, suppressionTotal, filesWithCounts } = countTotals(result.counts);
	const suppressionSummary =
		suppressionTotal > 0
			? `Biome suppressions ${suppressionTotal} across ${suppressions.size} rule(s)`
			: "no Biome suppressions";
	console.log(
		`${result.incomplete ? "Partial totals" : "Totals"}: explicit-any ${totals.get("explicit-any")} (includes as-any ${totals.get("as-any")}); as-any ${totals.get("as-any")}; non-null-assertion ${totals.get("non-null-assertion")}; ${suppressionSummary} in ${filesWithCounts} file(s).`,
	);
	if (suppressions.size > 0) {
		console.log("Suppression totals by rule/category:");
		for (const [rule, count] of [...suppressions].sort(([left], [right]) => compareText(left, right))) {
			console.log(`  ${rule}: ${count}`);
		}
	}
}

function printReport(root, result, baselinePath) {
	const errors = result.diagnostics.filter((diagnostic) => diagnostic.severity === "error");
	if (errors.length > 0) {
		console.log(`Scan incomplete: ${errors.length} error(s) prevented a complete conclusion.`);
		for (const error of errors) console.error(`  ${error.message}`);
	}
	console.log(
		"Type debt report (advisory; no source or baseline was modified). Explicit-any counts every any type node, including the any in as-any and <any>; as-any is a subset, so do not sum those categories.",
	);
	printTotals(result);
	console.log(`Scanned ${result.filesScanned} production source file(s) under packages/*/src. No files changed.`);
	if (result.incomplete) {
		console.log(
			"Incremental comparison skipped because the scan is incomplete; no conclusion about new debt was reached. No files changed.",
		);
		return;
	}
	const loaded = loadBaseline(baselinePath, displayPath(root, baselinePath));
	if (loaded.error) {
		console.error(loaded.error);
		console.log("Incremental comparison skipped; no conclusion about new debt was reached. No files changed.");
		return;
	}
	const changes = typeDebtChanges(result.snapshot, loaded.baseline);
	console.log("Incremental changes since baseline (per-file/category counts never offset each other):");
	if (changes.added.length === 0 && changes.removed.length === 0) {
		console.log("  No new or removed per-file category counts.");
	} else {
		for (const change of changes.added) {
			console.log(
				`  Added: ${change.file} [${change.category}] +${change.delta} (baseline ${change.previous} -> ${change.count})`,
			);
		}
		for (const change of changes.removed) {
			console.log(
				`  Removed: ${change.file} [${change.category}] -${change.delta} (baseline ${change.previous} -> ${change.count})`,
			);
		}
	}
}

function runUpdate(result, baselinePath) {
	const errors = result.diagnostics.filter((diagnostic) => diagnostic.severity === "error");
	if (errors.length > 0) {
		console.error("Refusing to update the type debt baseline from an incomplete scan:");
		for (const error of errors) console.error(`  ${error.message}`);
		console.error("No files changed.");
		process.exitCode = 1;
		return;
	}
	try {
		mkdirSync(dirname(baselinePath), { recursive: true });
		writeFileSync(baselinePath, `${JSON.stringify(result.snapshot, null, "\t")}\n`);
	} catch (error) {
		console.error(`Failed to write type debt baseline: ${messageOf(error)}`);
		process.exitCode = 1;
		return;
	}
	console.log(
		`Updated advisory type debt baseline (${result.counts.length} file/category count(s)). Review the diff before committing.`,
	);
}

function parseCli(args) {
	let rootInput = process.cwd();
	let baselineInput = BASELINE_FILE;
	let update = false;
	let rootSet = false;
	let baselineSet = false;
	for (let index = 0; index < args.length; index++) {
		const argument = args[index];
		if (argument === "--update") {
			if (update) return { error: "--update was provided more than once" };
			update = true;
			continue;
		}
		if (argument === "--root" || argument === "--baseline") {
			if (argument === "--root" && rootSet) return { error: "--root was provided more than once" };
			if (argument === "--baseline" && baselineSet) return { error: "--baseline was provided more than once" };
			const value = args[index + 1];
			if (!value || value.startsWith("--")) return { error: `${argument} requires a path` };
			index++;
			if (argument === "--root") {
				rootInput = value;
				rootSet = true;
			} else {
				baselineInput = value;
				baselineSet = true;
			}
			continue;
		}
		return { error: `Unknown argument ${JSON.stringify(argument)}` };
	}
	const root = resolve(process.cwd(), rootInput);
	const baselinePath = isAbsolute(baselineInput) ? baselineInput : resolve(root, baselineInput);
	return { root, baselinePath, update };
}

function main() {
	const parsed = parseCli(process.argv.slice(2));
	if (parsed.error) {
		console.error(parsed.error);
		console.error("Usage: node scripts/check-type-debt.mjs [--root <dir>] [--baseline <file>] [--update]");
		process.exitCode = 2;
		return;
	}
	let result;
	try {
		result = scanTypeDebt(parsed.root);
	} catch (error) {
		console.error(`Type debt scan failed: ${messageOf(error)}`);
		console.error("Scan incomplete; no conclusion was reached. No files changed.");
		if (parsed.update) process.exitCode = 1;
		return;
	}
	try {
		if (parsed.update) runUpdate(result, parsed.baselinePath);
		else printReport(parsed.root, result, parsed.baselinePath);
	} catch (error) {
		console.error(`Type debt report failed: ${messageOf(error)}`);
		console.error("Scan incomplete; no conclusion was reached. No files changed.");
		if (parsed.update) process.exitCode = 1;
	}
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) main();
