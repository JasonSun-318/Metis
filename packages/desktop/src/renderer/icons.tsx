// The application keeps semantic names here; only this module knows the library glyph mapping.
export interface IconProps extends Omit<ReiconProps, "weight" | "children"> {
	readonly weight?: "regular" | "light" | "bold" | "fill" | "duotone";
}

export type Icon = ReturnType<typeof icon>;

function icon(Component: IconComponent, { filled = false, rotate = 0 } = {}) {
	const Icon = forwardRef<SVGSVGElement, IconProps>(({ weight = "regular", size = "1em", ...props }, ref) => (
		<Component
			aria-hidden={props["aria-label"] || props["aria-labelledby"] || props.role ? undefined : true}
			focusable="false"
			{...props}
			ref={ref}
			size={size}
			style={rotate ? { ...props.style, rotate: `${rotate}deg`, transformOrigin: "center" } : props.style}
			weight={filled || weight === "fill" ? "Filled" : "Outline"}
		/>
	));
	Icon.displayName = Component.displayName;
	// Reicon writes static innerHTML when rendered. Preserve it across ordinary
	// parent updates so menu anchor observers do not see needless SVG mutations.
	return memo(Icon);
}

