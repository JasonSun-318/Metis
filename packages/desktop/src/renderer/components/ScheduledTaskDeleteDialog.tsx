import type { ScheduleTaskView } from "@metis/app-protocol";
import { useEffect, useRef, useState } from "react";
import { useTranslation } from "react-i18next";
import type { MetisDesktopApi } from "../../shared/desktop-api.ts";

export function ScheduledTaskDeleteDialog({ deleteSchedule, forceDeleteSessions, task, onClose, onDeleted }: {
	readonly deleteSchedule: MetisDesktopApi["deleteSchedule"];
	readonly forceDeleteSessions?: boolean;
	readonly task: ScheduleTaskView;
	readonly onClose: () => void;
	readonly onDeleted: (result: Awaited<ReturnType<MetisDesktopApi["deleteSchedule"]>>) => void;
}) {
	const { t } = useTranslation();
	const dialog = useRef<HTMLDialogElement>(null);
	const requestId = useRef(crypto.randomUUID());
	const [deleteGeneratedSessions, setDeleteGeneratedSessions] = useState(false);
	const deleteSessions = forceDeleteSessions ?? deleteGeneratedSessions;
	const [busy, setBusy] = useState(false);
	const [error, setError] = useState<string | null>(null);
	useEffect(() => {
		dialog.current?.showModal?.();
		return () => dialog.current?.close?.();
	}, []);
	const remove = async () => {
		setBusy(true);
		setError(null);
		try {
			onDeleted(await deleteSchedule({ requestId: requestId.current, taskId: task.id, deleteSessions }));
		} catch (cause) {
			setError(cause instanceof Error ? cause.message : "The scheduled task could not be moved to Trash.");
		} finally {
			setBusy(false);
		}
	};
	return (
		<dialog
			aria-labelledby="scheduled-task-delete-title"
			className="scheduled-task-delete-dialog"
			onCancel={(event) => { event.preventDefault(); if (!busy) onClose(); }}
			onMouseDown={(event) => { if (event.target === event.currentTarget && !busy) onClose(); }}
			ref={dialog}
		>
			<form method="dialog" onSubmit={(event) => { event.preventDefault(); void remove(); }}>
				<h2 id="scheduled-task-delete-title">{t("Delete “{{name}}”?", { name: task.name })}</h2>
				<p>
					{t("Future runs stop immediately.")}{" "}
					{task.target.workspace === "task"
						? t("Its dedicated task workspace is moved to Trash. Any additionally authorized folder is unchanged.")
						: t("The selected project folder is unchanged.")}
				</p>
				{forceDeleteSessions === undefined ? (
					<label className="scheduled-task-delete-option">
						<input checked={deleteSessions} disabled={busy} onChange={(event) => setDeleteGeneratedSessions(event.target.checked)} type="checkbox" />
						<span><strong>{t("Also delete all session files generated by this task")}</strong><small>{t("Moves generated Scheduled sessions and their owned images, attachments, tool outputs, Subagent data, and document-work data to Trash.")}</small></span>
					</label>
				) : (
					<p>{t("Moves generated Scheduled sessions and their owned images, attachments, tool outputs, Subagent data, and document-work data to Trash.")}</p>
				)}
				{error && <p className="scheduled-task-form-error" role="alert">{t(error)}</p>}
				<footer><button className="button-secondary" disabled={busy} onClick={onClose} type="button">{t("Cancel")}</button><button className="scheduled-task-danger" disabled={busy} type="submit">{t(busy ? "Deleting…" : "Delete")}</button></footer>
			</form>
		</dialog>
	);
}
