function isAppLocale(value: unknown): value is AppLocale {
	return value === "en" || value === "zh-CN";
}

export function loadLocale(storage: Pick<Storage, "getItem">): AppLocale {
	try {
		const value = storage.getItem(APP_LOCALE_STORAGE_KEY);
		return isAppLocale(value) ? value : "en";
	} catch {
		return "en";
	}
}

const initialLocale = typeof localStorage === "undefined" ? "en" : loadLocale(localStorage);
if (typeof document !== "undefined") document.documentElement.lang = initialLocale;

void i18n.use(initReactI18next).init({
	resources: { en: { translation: {} }, "zh-CN": { translation: zhCN } },
	lng: initialLocale,
	fallbackLng: "en",
	supportedLngs: ["en", "zh-CN"],
	load: "currentOnly",
	keySeparator: false,
	nsSeparator: false,
	initAsync: false,
	interpolation: { escapeValue: false },
	react: { useSuspense: false },
});

export async function setLocale(
	locale: AppLocale,
	storage: Pick<Storage, "setItem"> | undefined = typeof localStorage === "undefined" ? undefined : localStorage,
): Promise<void> {
	try {
		storage?.setItem(APP_LOCALE_STORAGE_KEY, locale);
	} catch {
		// The active locale still changes when persistence is unavailable.
	}
	if (typeof document !== "undefined") document.documentElement.lang = locale;
	await i18n.changeLanguage(locale);
}

export function localeForIntl(language = i18n.resolvedLanguage): "en-US" | "zh-CN" {
	return language === "zh-CN" ? "zh-CN" : "en-US";
}

